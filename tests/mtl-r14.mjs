import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {loadRegistry,loadRevision,sceneOptions} from "../tools/map-viewer/model.js";
import {instantiateBuilding,validateLibrary} from "../engine/mfs/template-library.js";
import {placementIssues} from "../engine/mfs/furniture-placement.js";
import {roomTopology} from "../engine/mfs/room-topology.js";
import {decorationIssues} from "../engine/mfs/decorations.js";
import {validateRuralAreas} from "../engine/mfs/rural-areas.js";
import {revisionChoices} from "../tools/map-viewer/revision-menu.js";
const read=async p=>JSON.parse(await readFile(new URL("../"+p,import.meta.url),"utf8"));
const fetcher=async p=>{try{const v=await read(p);return {ok:true,json:async()=>v};}catch{return {ok:false};}};
const es=await loadRegistry("maps/",fetcher);
const p=await loadRevision("maps/",es.find(e=>e.mapId==="mtl_gallery_001"&&e.mapRevision===14),fetcher);
assert.equal(p.report.counts.ERROR,0);assert.equal(p.report.counts.WARNING,0);assert.equal(p.report.playable,false);
assert.equal(p.data.buildings.length,163);assert.equal(p.data.interiors.length,229);assert.equal(sceneOptions(p).length,230);
assert.equal(p.report.stats.stations,2491);assert.equal(validateRuralAreas(p.manifest,p.data).length,0);
assert.ok(revisionChoices(es)[0].mapRevision>=14);
const old=await loadRevision("maps/",es.find(e=>e.mapId==="mtl_gallery_001"&&e.mapRevision===13),fetcher);
assert.deepEqual(p.data.portals,old.data.portals);
assert.deepEqual(p.data.buildings.map(b=>b.geometry),old.data.buildings.map(b=>b.geometry));
const lib=validateLibrary(await read("templates/mtl/catalog-v14.json")),audit=await read("templates/mtl/audit-candidates-0.3.44.json");
assert.equal(audit.reports.length,163);assert.equal(audit.stats.floors,229);assert.equal(audit.stats.changedModels,161);
let count=0;for(const t of lib.buildings)for(const r of t.orientations){const a=instantiateBuilding({...lib,buildings:[t]},t.id,t.version,{mapId:"audit",id:"audit.b1",parcelId:"audit.p1",x:1,y:1,rotation:r});for(const f of a.interiors){count++;assert.equal(placementIssues(f,a.portals).length,0);assert.equal(roomTopology(f,a.portals).issues.length,0);assert.equal(decorationIssues(f,a.portals).length,0);}}assert.equal(count,916);
console.log("MTL r14 regression passed");
